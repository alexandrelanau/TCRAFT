from pathlib import Path

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QFileDialog,
    QGroupBox,
    QHBoxLayout,
    QLabel,
    QLineEdit,
    QMainWindow,
    QMessageBox,
    QPlainTextEdit,
    QProgressBar,
    QPushButton,
    QTabWidget,
    QVBoxLayout,
    QWidget,
)

from TCRAFT.Generate import generate_cdr3_oligos
from TCRAFT.Validate import validate_cdr3_oligos

from .worker import TCRAFTWorker


class MainWindow(QMainWindow):

    def __init__(self):
        super().__init__()

        self.worker = None

        self.setWindowTitle("TCRAFT")
        self.resize(900, 650)

        self.build_ui()

    def build_ui(self):
        central = QWidget()
        layout = QVBoxLayout(central)

        title = QLabel("TCRAFT")
        title.setStyleSheet(
            "font-size: 28px; font-weight: bold; padding: 10px;"
        )

        subtitle = QLabel(
            "TCR library generation and assembly validation"
        )
        subtitle.setStyleSheet(
            "font-size: 14px; color: #666; padding-bottom: 10px;"
        )

        layout.addWidget(title)
        layout.addWidget(subtitle)

        self.tabs = QTabWidget()

        self.generate_tab = self.create_generate_tab()
        self.validate_tab = self.create_validate_tab()

        self.tabs.addTab(self.generate_tab, "Generate")
        self.tabs.addTab(self.validate_tab, "Validate")

        layout.addWidget(self.tabs)

        self.progress = QProgressBar()
        self.progress.setRange(0, 0)
        self.progress.hide()

        layout.addWidget(self.progress)

        self.log_output = QPlainTextEdit()
        self.log_output.setReadOnly(True)
        self.log_output.setPlaceholderText(
            "TCRAFT output will appear here..."
        )

        layout.addWidget(self.log_output)

        self.setCentralWidget(central)

    def create_generate_tab(self):
        widget = QWidget()
        layout = QVBoxLayout(widget)

        input_group = QGroupBox("Input TCR list")
        input_layout = QHBoxLayout(input_group)

        self.generate_input = QLineEdit()
        self.generate_input.setPlaceholderText(
            "Select a CSV file containing your TCR sequences"
        )

        input_button = QPushButton("Browse...")
        input_button.clicked.connect(
            lambda: self.select_file(self.generate_input)
        )

        input_layout.addWidget(self.generate_input)
        input_layout.addWidget(input_button)

        layout.addWidget(input_group)

        output_group = QGroupBox("Output directory")
        output_layout = QHBoxLayout(output_group)

        self.generate_output = QLineEdit()
        self.generate_output.setPlaceholderText(
            "Leave empty to use the default output directory"
        )

        output_button = QPushButton("Browse...")
        output_button.clicked.connect(
            lambda: self.select_directory(self.generate_output)
        )

        output_layout.addWidget(self.generate_output)
        output_layout.addWidget(output_button)

        layout.addWidget(output_group)

        self.generate_button = QPushButton(
            "Generate CDR3 oligos"
        )
        self.generate_button.setMinimumHeight(45)
        self.generate_button.clicked.connect(
            self.run_generate
        )

        layout.addWidget(self.generate_button)
        layout.addStretch()

        return widget

    def create_validate_tab(self):
        widget = QWidget()
        layout = QVBoxLayout(widget)

        input_group = QGroupBox("Input oligo file")
        input_layout = QHBoxLayout(input_group)

        self.validate_input = QLineEdit()
        self.validate_input.setPlaceholderText(
            "Select a CSV generated by TCRAFT"
        )

        input_button = QPushButton("Browse...")
        input_button.clicked.connect(
            lambda: self.select_file(self.validate_input)
        )

        input_layout.addWidget(self.validate_input)
        input_layout.addWidget(input_button)

        layout.addWidget(input_group)

        output_group = QGroupBox("Output directory")
        output_layout = QHBoxLayout(output_group)

        self.validate_output = QLineEdit()
        self.validate_output.setPlaceholderText(
            "Leave empty to use the default output directory"
        )

        output_button = QPushButton("Browse...")
        output_button.clicked.connect(
            lambda: self.select_directory(self.validate_output)
        )

        output_layout.addWidget(self.validate_output)
        output_layout.addWidget(output_button)

        layout.addWidget(output_group)

        self.validate_button = QPushButton(
            "Validate assembly"
        )
        self.validate_button.setMinimumHeight(45)
        self.validate_button.clicked.connect(
            self.run_validate
        )

        layout.addWidget(self.validate_button)
        layout.addStretch()

        return widget

    def select_file(self, line_edit):
        filename, _ = QFileDialog.getOpenFileName(
            self,
            "Select CSV file",
            "",
            "CSV files (*.csv);;All files (*)",
        )

        if filename:
            line_edit.setText(filename)

    def select_directory(self, line_edit):
        directory = QFileDialog.getExistingDirectory(
            self,
            "Select output directory",
        )

        if directory:
            line_edit.setText(directory)

    def set_running(self, running):
        self.generate_button.setEnabled(not running)
        self.validate_button.setEnabled(not running)

        if running:
            self.progress.show()
        else:
            self.progress.hide()

    def run_generate(self):
        input_path = self.generate_input.text().strip()
        output_dir = self.generate_output.text().strip() or None

        if not input_path:
            QMessageBox.warning(
                self,
                "Missing input",
                "Please select a CSV input file.",
            )
            return

        if not Path(input_path).is_file():
            QMessageBox.warning(
                self,
                "Invalid input",
                "The selected input file does not exist.",
            )
            return

        self.start_worker(
            generate_cdr3_oligos,
            input_path,
            output_dir,
        )

    def run_validate(self):
        input_path = self.validate_input.text().strip()
        output_dir = self.validate_output.text().strip() or None

        if not input_path:
            QMessageBox.warning(
                self,
                "Missing input",
                "Please select a CSV input file.",
            )
            return

        if not Path(input_path).is_file():
            QMessageBox.warning(
                self,
                "Invalid input",
                "The selected input file does not exist.",
            )
            return

        self.start_worker(
            validate_cdr3_oligos,
            input_path,
            output_dir,
        )

    def start_worker(self, function, input_path, output_dir):
        self.log_output.clear()
        self.log_output.appendPlainText(
            f"Input: {input_path}"
        )

        if output_dir:
            self.log_output.appendPlainText(
                f"Output: {output_dir}"
            )

        self.log_output.appendPlainText("")
        self.log_output.appendPlainText(
            "Starting TCRAFT..."
        )

        self.set_running(True)

        self.worker = TCRAFTWorker(
            function,
            input_path,
            output_dir,
        )

        self.worker.log.connect(
            self.log_output.appendPlainText
        )

        self.worker.error.connect(
            self.on_worker_error
        )

        self.worker.finished.connect(
            self.on_worker_finished
        )

        self.worker.start()

    def on_worker_finished(self):
        self.set_running(False)

        self.log_output.appendPlainText("")
        self.log_output.appendPlainText(
            "TCRAFT completed successfully."
        )

        QMessageBox.information(
            self,
            "TCRAFT",
            "The operation completed successfully.",
        )

    def on_worker_error(self, message):
        self.set_running(False)

        self.log_output.appendPlainText("")
        self.log_output.appendPlainText(
            f"ERROR: {message}"
        )

        QMessageBox.critical(
            self,
            "TCRAFT error",
            message,
        )